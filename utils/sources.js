/**
 * 尺寸数据与出处。
 *
 * 说课最怕一件事：讲到一半被人问"这数儿哪来的"。凡是屏幕上出现的尺寸，
 * 这里都查得到它是文献值、通行说法，还是本模型自己算的。这三者必须分开列，
 * 混在一起最要命——读的人会以为水力数字也是史料。
 *
 * 数值尽量从 bridge.js / hydro.js 现取，不在这里抄第二遍。抄一遍看着省事，
 * 等哪天改了几何，面板上就留着一个和画面对不上的旧数，比没有出处更糟。
 *
 * 分栏（见 TABS）是有原因的：全摞成一屏要滚两屏半，录屏时很难看。
 * 按 主体 / 敞肩 / 石作 / 沿革 / 年表 分开，前四栏各自一屏放得下，
 * 讲解时点一下就换；年表条目多，摆在最后一栏，本来就该顺着往下滚。
 * 往哪一栏加东西之前，先掂量一下那栏还放不放得下。
 */

